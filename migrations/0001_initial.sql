-- PostgreSQL 17，无业务扩展。只由本项目 migrator 执行。
CREATE TABLE app.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  password_hash text NOT NULL,
  email_verified_at text,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE UNIQUE INDEX users_email_unique ON app.users (email);
CREATE TABLE app.sessions (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL,
  expires_at text NOT NULL,
  created_at text NOT NULL
);
CREATE INDEX sessions_user_idx ON app.sessions (user_id);
CREATE TABLE app.verification_tokens (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL,
  expires_at text NOT NULL,
  created_at text NOT NULL
);
CREATE INDEX verification_user_idx ON app.verification_tokens (user_id);
CREATE TABLE app.items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer,
  category text NOT NULL DEFAULT 'phone',
  title text NOT NULL,
  provider text NOT NULL DEFAULT '',
  amount double precision,
  currency text NOT NULL DEFAULT 'CNY',
  cycle text NOT NULL DEFAULT '',
  start_date text NOT NULL DEFAULT '',
  next_date text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'active',
  detail text NOT NULL DEFAULT '{}',
  note text NOT NULL DEFAULT '',
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX items_user_idx ON app.items (user_id);
